"""Host self-test of the power-loss log, restore math and image-transmission
stream parser (mt_selftest.c).

1. Generates build/mt/Arm_L_task.h from the joint limits / zero points of
   APP/Arm_L_task.h, and checks the constants copied into stub_mt/can_bsp.h
   against APP/Compat/can_bsp.h.
2. Compiles APP/multi_turn_store.c, APP/multi_turn_restore.c,
   Components/Device/Src/Image_Transmission.c and CRC.c with gcc
   (-Wall -Wextra -Werror), once with MT_RESTORE_ENABLE=0 and once with 1.
3. Runs both binaries.

Nothing runs on the STM32; this does not replace a Keil build.

Usage:  python tools/selftest/mt_selftest.py
"""

import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(os.path.dirname(HERE))
APP = os.path.join(PROJECT, "APP")
DEV_INC = os.path.join(PROJECT, "Components", "Device", "Inc")
DEV_SRC = os.path.join(PROJECT, "Components", "Device", "Src")
ALG_INC = os.path.join(PROJECT, "Components", "Algorithm", "Inc")
ALG_SRC = os.path.join(PROJECT, "Components", "Algorithm", "Src")
STUB = os.path.join(HERE, "stub_mt")
BUILD = os.path.join(HERE, "build", "mt")


def compiler():
    for cand in (os.environ.get("CC"), "gcc", r"E:\mingw64\bin\gcc.exe", "cc", "clang"):
        if cand and shutil.which(cand):
            return shutil.which(cand)
    sys.exit("no C compiler found (set CC or install gcc)")


def defines(path, names):
    text = open(path, encoding="utf-8", errors="replace").read()
    out = {}
    for n in names:
        m = re.search(r"^#define\s+%s\s+(\S+)" % re.escape(n), text, re.M)
        if not m:
            sys.exit("%s not found in %s" % (n, path))
        out[n] = m.group(1)
    return out


def main():
    os.makedirs(BUILD, exist_ok=True)
    names = []
    for j in ("J1", "J2", "J3", "J4", "J5", "J6", "Grip"):
        names += ["%s_Max_position" % j, "%s_Min_position" % j]
    names += ["J%d_zero_position" % i for i in range(1, 7)] + ["grip_zero_position"]
    vals = defines(os.path.join(APP, "Arm_L_task.h"), names)
    with open(os.path.join(BUILD, "Arm_L_task.h"), "w", newline="\n") as f:
        f.write("/* Generated by mt_selftest.py from APP/Arm_L_task.h */\n")
        f.write("#ifndef MT_GEN_ARM_L_TASK_H\n#define MT_GEN_ARM_L_TASK_H\n")
        for n in names:
            f.write("#define %s %s\n" % (n, vals[n]))
        f.write("#endif\n")
    print("joint limits / zero points taken from APP/Arm_L_task.h")

    real = defines(os.path.join(APP, "Compat", "can_bsp.h"),
                   ["JOINT_ERR_FAULT_MIN", "JOINT_FEEDBACK_TIMEOUT_MS", "JOINT_ALL_MASK"])
    real["P_MIN"] = re.search(r"#define P_MIN\s+(\S+)", open(os.path.join(APP, "Compat", "can_bsp.h")).read()).group(1)
    real["P_MAX"] = re.search(r"#define P_MAX\s+(\S+)", open(os.path.join(APP, "Compat", "can_bsp.h")).read()).group(1)
    stub = defines(os.path.join(STUB, "can_bsp.h"), list(real))
    bad = [n for n in real if real[n] != stub[n]]
    if bad:
        sys.exit("stub_mt/can_bsp.h differs from APP/Compat/can_bsp.h: %s" % bad)
    print("stub_mt/can_bsp.h constants match APP/Compat/can_bsp.h")

    # A quoted include looks in the source directory first: compile a copy
    # of multi_turn_restore.c so it gets the generated Arm_L_task.h.
    shutil.copy(os.path.join(APP, "multi_turn_restore.c"), BUILD)

    cc = compiler()
    srcs = [os.path.join(HERE, "mt_selftest.c"),
            os.path.join(APP, "multi_turn_store.c"),
            os.path.join(BUILD, "multi_turn_restore.c"),
            os.path.join(DEV_SRC, "Image_Transmission.c"),
            os.path.join(ALG_SRC, "CRC.c")]
    ok = True
    for enable in (0, 1):
        exe = os.path.join(BUILD, "mt_selftest_%d.exe" % enable)
        cmd = [cc, "-std=c11", "-O1", "-Wall", "-Wextra", "-Werror",
               "-Wno-unused-parameter", "-Wno-missing-field-initializers",
               "-DMT_STORE_HOST_TEST", "-DMT_RESTORE_ENABLE=%d" % enable,
               "-I", BUILD, "-I", STUB, "-I", APP, "-I", DEV_INC, "-I", ALG_INC,
               "-o", exe] + srcs + ["-lm"]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            print(r.stdout + r.stderr)
            sys.exit("compile failed (MT_RESTORE_ENABLE=%d)" % enable)
        r = subprocess.run([exe], capture_output=True, text=True)
        print(r.stdout.strip())
        ok = ok and r.returncode == 0
    print("MT SELFTEST OK" if ok else "MT SELFTEST FAILED")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
